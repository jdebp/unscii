use Getopt::Long;

$result = GetOptions (
             "copyright|c=s" => \$copyright, # Copyright string
             "font|f=s"      => \$font_name, # XLFD FAMILY_NAME
             "rows|r=i"      => \$vpixels,   # XLFD PIXEL_SIZE; vertical pixels
             "version|v=s"   => \$version,   # Version of this font
             "variant|V=s"   => \$variant
             );

if (not $font_name) {
   $font_name = "Unscii";
}
if (not $vpixels) {
   $vpixels  = 8;
}
if (not $version) {
   $version = "1.2";
}
if (not $foundry) {
   $foundry = "Unscii";
}
if (not $variant) {
   $variant = "Medium";
}

if($vpixels==16)
{
  ($caphgt,$xhgt,$asc,$desc,$undpos)=(11,7,13,3,1);
} else
{
  ($caphgt,$xhgt,$asc,$desc,$undpos)=(7,5,7,1,0);
}

$point_size   = $vpixels;
$point_size10 = 10 * $point_size;

$foundrylowcase = $foundry;
$founrdylowcase =~ tr/A-Z/a-z/;

while (<>) {
	chomp;
	$glyph{hex($1)} = $2 if /^([0-9a-fA-F]+):([0-9a-fA-F]+)/;
}
@chars = sort {$a <=> $b} keys %glyph;
$nchars = $#chars + 1;

print "# Generated by hex2yaff
name: ${font_name}
foundry: ${foundry}
encoding: ISO10646
default-char: default
spacing: monospace
size: ${vpixels}
copyright: ${copyright}
revision: ${version}
variant: ${variant}
size10: ${point_size10}
underline-position: ${undpos}
cap-height: ${caphgt}
x-height: ${xhgt}
chars: $nchars\n\n";

foreach $character (@chars)
{
	$glyph = $glyph{$character};
	$width = length ($glyph) / $vpixels;  # hex digits per row
	printf "0x%06X:\n", $character;
	foreach ($glyph =~ /.{$width}/g) {
		print "\t";
		foreach ($_ =~ /../g) {
			$bits = sprintf ("%08b", hex($_));
			$bits =~ tr/01/.@/;
			print $bits;
		}
		print "\n"
	}
	print "\n"
}
